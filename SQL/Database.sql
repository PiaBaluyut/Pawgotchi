CREATE TABLE pet (
pet_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR2 (50) NOT NULL,
species VARCHAR2 (3) NOT NULL,
DateCreated DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE status (
status_id NUMBER (10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
pet_id NUMBER (10) NOT NULL,
hunger NUMBER (15),
happiness NUMBER (15),
energy NUMBER (15),
LastUpdated DATE DEFAULT SYSDATE,
CONSTRAINT fk_status_pet FOREIGN KEY (pet_id)
    REFERENCES pet(pet_id)
);

CREATE TABLE activities (
activity_id NUMBER (10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
pet_id NUMBER (10) NOT NULL,
activity_type VARCHAR2 (50),
activity_date DATE DEFAULT SYSDATE,
CONSTRAINT fk_activities_pet FOREIGN KEY (pet_id)
    REFERENCES pet(pet_id)
);

CREATE TABLE messages (
message_id NUMBER (10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
pet_id NUMBER (10) NOT NULL,
message_text VARCHAR2 (255),
message_type VARCHAR2 (50),
CONSTRAINT fk_messages_pet FOREIGN KEY (pet_id)
    REFERENCES pet(pet_id)
);
